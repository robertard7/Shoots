# -----------------------------
# Helpers: safe array + scanning
# -----------------------------
function Get-TypeDeclFiles {
  param(
    [Parameter(Mandatory=$true)][string]$TypeName
  )

  $rx = "(?m)^\s*(public\s+)?(sealed\s+)?(partial\s+)?(class|record|struct|enum)\s+$TypeName\b"

  $hits = Get-ChildItem -Path $uiDir -Recurse -Filter *.cs |
    Where-Object { Select-String -LiteralPath $_.FullName -Pattern $rx -Quiet } |
    Select-Object -ExpandProperty FullName

  if ($null -eq $hits) { return @() }
  return @($hits)
}

function Disable-FileByIfFalse {
  param(
    [Parameter(Mandatory=$true)][string]$Path
  )

  $txt = Get-Content -LiteralPath $Path -Raw
  if ($txt -match "^\s*#if\s+false\b") {
    Hit "already disabled: $Path"
    return
  }

  $disabled = "#if false`r`n" + $txt.TrimEnd() + "`r`n#endif`r`n"
  Set-Content -LiteralPath $Path -Value $disabled -NoNewline
  Hit "DISABLED: $Path"
}

# Removes a single type definition block by naive brace matching.
# Assumes the type is a normal C# type with a body: ... { ... }
function Remove-TypeBlockFromFile {
  param(
    [Parameter(Mandatory=$true)][string]$FilePath,
    [Parameter(Mandatory=$true)][string]$TypeName
  )

  $text = Get-Content -LiteralPath $FilePath -Raw
  $rxStart = "(?m)^\s*(public\s+)?(sealed\s+)?(partial\s+)?(class|record|struct|enum)\s+$TypeName\b.*$"

  $m = [regex]::Match($text, $rxStart)
  if (-not $m.Success) {
    return $false
  }

  $startIdx = $m.Index

  # Find the first '{' after the declaration line
  $braceOpen = $text.IndexOf("{", $m.Index)
  if ($braceOpen -lt 0) {
    # If no body brace, we can't safely remove. Bail.
    Warn "Found declaration for $TypeName but couldn't find '{' in $FilePath"
    return $false
  }

  $depth = 0
  $i = $braceOpen
  for (; $i -lt $text.Length; $i++) {
    $ch = $text[$i]
    if ($ch -eq "{") { $depth++ }
    elseif ($ch -eq "}") {
      $depth--
      if ($depth -eq 0) {
        # include closing brace
        $endIdx = $i + 1

        # Extend to consume trailing whitespace/newlines
        while ($endIdx -lt $text.Length -and ($text[$endIdx] -eq "`r" -or $text[$endIdx] -eq "`n" -or $text[$endIdx] -eq " " -or $text[$endIdx] -eq "`t")) {
          # stop if we hit a non-whitespace after at least one blank line? no, consume all contiguous whitespace
          $endIdx++
        }

        $before = $text.Substring(0, $startIdx)
        $after  = $text.Substring($endIdx)

        $newText = ($before.TrimEnd() + "`r`n`r`n" + $after.TrimStart())
        Set-Content -LiteralPath $FilePath -Value $newText -NoNewline
        Hit "REMOVED duplicate type '$TypeName' block from: $FilePath"
        return $true
      }
    }
  }

  Warn "Could not match braces removing $TypeName from $FilePath (unbalanced braces?)"
  return $false
}

