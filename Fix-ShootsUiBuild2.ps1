  Hit "found $($rootFiles.Count) declaration(s). OK."
} else {
  Hit "found $($rootFiles.Count) declaration(s):"
  foreach ($f in $rootFiles) { Hit $f }

  foreach ($f in $rootFiles) {
    if ($f -ieq $rootPreferred) {
      Hit "keeping enabled: $f"
      continue
    }

    # Prefer surgical removal over disabling whole file
    $removed = Remove-TypeBlockFromFile -FilePath $f -TypeName "RootFsDescriptor"
    if (-not $removed) {
      Warn "Couldn't surgically remove RootFsDescriptor from $f. Disabling file as fallback."
      Disable-FileByIfFalse -Path $f
    }
  }
}

